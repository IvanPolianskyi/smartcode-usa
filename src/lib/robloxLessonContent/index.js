function createPlaceholder(lessonId, title, locale = 'uk') {
  const ukContent =
    'Контент цього уроку ще готується. Продовжуй попередні уроки або звернися до викладача на онлайн-занятті. Ти вже можеш відкрити наступні теми в програмі курсу - вони розблокуються за розкладом.'
  const enContent =
    'This lesson is being prepared. Continue previous lessons or book a live class with your teacher. You can still browse the course outline - lessons unlock on your schedule.'

  return {
    lessonId,
    title,
    learningObjectives: [
      locale === 'en'
        ? 'Lesson content coming soon'
        : 'Матеріал уроку буде додано найближчим часом',
    ],
    estimatedTime: 60,
    theory: {
      sections: [
        {
          title,
          content: locale === 'en' ? enContent : ukContent,
        },
      ],
    },
    practiceTask: null,
    comingSoon: true,
  }
}

function resolveLocaleEntry(entry, locale) {
  if (!entry) return null
  if (entry.uk || entry.en) {
    const picked = locale === 'en' ? entry.en : entry.uk
    if (!picked) return locale === 'en' ? entry.uk : entry.en
    return { ...picked, lessonId: picked.lessonId || entry.uk?.lessonId || entry.en?.lessonId }
  }
  return entry
}

