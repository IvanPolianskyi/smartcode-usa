function fixSpacing(text) {
  return text
    .replace(/\*\*([^*]+)\*\*\*\*([^*]+)\*\*/g, '**$1** **$2**')
    .replace(/\*\*\*\*/g, '**')
    .replace(/`([A-Za-z_][\w.$]*?)`([а-яА-ЯіїєґІЇЄҐ«(])/g, '`$1` $2')
    .replace(/([а-яА-ЯіїєґІЇЄҐ».)])`([A-Za-z_$])/g, '$1 `$2')
    .replace(/`([A-Za-z_][\w.$]*?)`([A-Za-z_$])/g, '`$1` $2')
    .replace(/([а-яА-ЯіїєґІЇЄҐ0-9])`([A-Za-z_])/g, '$1 `$2')
    .replace(/`([A-Za-z_][\w.$]*?)`([0-9])/g, '`$1` $2')
    .replace(/→`([^`]+)`([0-9])/g, '→ `$1` $2')
    .replace(/`([^`\n]+)`([0-9])/g, '`$1` $2')
    .replace(/  +/g, ' ')
}

function fixContent(text) {
  let out = text
  for (const [from, to] of PROSE_FIXES) {
    out = out.split(from).join(to)
  }
  return fixSpacing(out)
}

const files = fs.readdirSync(ukDir).filter((f) => f.startsWith('module') && f.endsWith('.js'))
let updated = 0

for (const file of files) {
  const filePath = path.join(ukDir, file)
  const before = fs.readFileSync(filePath, 'utf8')
  const after = fixContent(before)
  if (after !== before) {
    fs.writeFileSync(filePath, after, 'utf8')
    updated++
    console.log(`fixed ${file}`)
  }
}

console.log(`Done. Updated ${updated} files.`)
