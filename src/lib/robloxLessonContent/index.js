const allLessonIds = robloxCurriculum.modules.flatMap((m) =>
  (m.lessons || []).map((l) => l.lessonId)
)

function buildMapForLocale(locale) {
  const placeholders = Object.fromEntries(
    allLessonIds
      .filter((id) => !bilingual[id])
      .map((id) => {
        const meta = robloxCurriculum.modules
          .flatMap((m) => m.lessons)
          .find((l) => l.lessonId === id)
        return [id, createPlaceholder(id, meta?.title || id, locale)]
      })
  )

  const resolved = Object.fromEntries(
    Object.entries(bilingual).map(([id, entry]) => [
      id,
      resolveLocaleEntry(entry, locale),
    ])
  )

  return { ...placeholders, ...resolved }
}

const cache = { uk: null, en: null }

export const robloxLessonContentMap = buildMapForLocale('uk')

export function getRobloxLessonContent(lessonId, locale = 'uk') {
  const loc = locale === 'en' ? 'en' : 'uk'
  if (!cache[loc]) cache[loc] = buildMapForLocale(loc)
  return cache[loc][lessonId] || null
}

/** Count of lessons with full practice (sellable) */
export function getRobloxEnLessonStats() {
  const enMap = buildMapForLocale('en')
  const total = allLessonIds.length
  const ready = allLessonIds.filter((id) => enMap[id] && !enMap[id].comingSoon).length
  return { total, ready }
}

export function getRobloxUkLessonStats() {
  const ukMap = buildMapForLocale('uk')
  const total = allLessonIds.length
  const ready = allLessonIds.filter((id) => ukMap[id] && !ukMap[id].comingSoon).length
  return { total, ready }
}
